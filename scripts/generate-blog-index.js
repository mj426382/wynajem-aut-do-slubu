/**
 * Builds src/blog/index.generated.js – post METADATA only (no bodies) – from src/blog/posts/*.js.
 *
 * Listing pages (home, /blog) need titles and excerpts only; shipping every article body in the main bundle
 * made each page heavier with every post. Bodies load lazily per slug (src/blog/index.js) and eagerly during the
 * prerender (src/blog/content.server.js). Run automatically by `npm run dev` and `npm run build`.
 */
import { readdirSync, readFileSync, writeFileSync } from 'fs'
import { resolve, dirname } from 'path'
import { fileURLToPath } from 'url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const postsDir = resolve(__dirname, '../src/blog/posts')
const outFile = resolve(__dirname, '../src/blog/index.generated.js')

export function field(src, name) {
  const m = src.match(new RegExp(`^export const ${name} = '((?:[^'\\\\]|\\\\.)*)'`, 'm'))
  return m ? m[1].replace(/\\'/g, "'").replace(/\\\\/g, '\\') : null
}

export function readPostMeta(file) {
  const src = readFileSync(resolve(postsDir, file), 'utf-8')
  const slug = field(src, 'slug')
  if (!slug) throw new Error(`${file}: missing "export const slug"`)
  if (`${slug}.js` !== file) throw new Error(`${file}: the file must be named after its slug (${slug}.js)`)
  const date = field(src, 'date')
  if (!/^\d{4}-\d{2}-\d{2}$/.test(date ?? '')) throw new Error(`${file}: date must be YYYY-MM-DD`)
  const modifiedAt = field(src, 'modifiedAt') ?? date
  const tagsMatch = src.match(/^export const tags = (\[[^\]]*\])/m)
  const tags = tagsMatch ? [...tagsMatch[1].matchAll(/'((?:[^'\\]|\\.)*)'/g)].map((m) => m[1].replace(/\\'/g, "'")) : []
  return {
    slug,
    title: field(src, 'title') ?? slug,
    metaTitle: field(src, 'metaTitle') ?? field(src, 'title') ?? slug,
    metaDescription: field(src, 'metaDescription') ?? field(src, 'excerpt') ?? '',
    excerpt: field(src, 'excerpt') ?? '',
    date,
    modifiedAt,
    readTime: Number(src.match(/^export const readTime = (\d+)/m)?.[1] ?? 5),
    category: field(src, 'category') ?? 'Porady',
    emoji: field(src, 'emoji') ?? '💍',
    tags,
  }
}

export function allPostMeta() {
  return readdirSync(postsDir)
    .filter((f) => f.endsWith('.js'))
    .map(readPostMeta)
    .sort((a, b) => (a.date < b.date ? 1 : a.date > b.date ? -1 : a.slug.localeCompare(b.slug)))
}

const posts = allPostMeta()
const content = `// GENERATED by scripts/generate-blog-index.js – do not edit by hand.
// Metadata of every post (no bodies). Bodies load lazily via src/blog/index.js.
export const blogIndex = ${JSON.stringify(posts, null, 2)}
`
writeFileSync(outFile, content, 'utf-8')
console.log(`✅ src/blog/index.generated.js (${posts.length} posts, metadata only)`)
